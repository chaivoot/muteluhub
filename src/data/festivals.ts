import type { GoalSlug } from '@/lib/goals';

/**
 * เทศกาล: URL ไม่มีปี (/festival/[slug]) เนื้อหาอัปเดตทุกปี
 * วันที่แยกเป็นรายปีใน dates (ตาราง festival_dates ใน spec)
 * ใส่เฉพาะวันที่ที่ยืนยันแล้วเท่านั้น
 */
export interface FestivalDate {
  year: number; // ค.ศ.
  start: string; // YYYY-MM-DD
  end: string;
  prep?: string;
  notes?: string;
}

export interface SourcedText {
  text: string;
  source?: string;
}

export interface FestivalVenue {
  name: string;
  province: string;
  placeName?: string;
  /** วันจัดงานปีนี้ (ถ้าประกาศแล้ว) */
  dates?: string;
  description: string;
  sources: string[];
}

export interface FestivalFaq {
  q: string;
  a: string;
  source?: string;
}

/** หัวข้อเนื้อหาเพิ่มเติม เช่น กิจกรรมช่วงเทศกาล ข้อควรระวังตามความเชื่อ */
export interface FestivalSection {
  title: string;
  /** cards = การ์ด (ค่าเริ่มต้น), checklist = รายการของไหว้ติ๊กได้, steps = ขั้นตอนเรียงเลข */
  style?: 'cards' | 'checklist' | 'steps';
  intro?: string;
  items: { name: string; text: string; source?: string }[];
}

/** เนื้อหาหน้าเทศกาล อัปเดตทุกปี (URL ไม่มีปี) ทุกข้อเท็จจริงต้องมีแหล่งอ้างอิง */
export interface FestivalContent {
  intro: string;
  /** หมายเหตุวันตามจันทรคติ */
  lunarNote?: string;
  /** หัวข้อของ rules (ค่าเริ่มต้น ข้อควรปฏิบัติ) */
  rulesTitle?: string;
  rules: SourcedText[];
  /** หัวข้อเพิ่มเติม แสดงต่อจาก rules */
  sections?: FestivalSection[];
  /** หัวข้อของรายการพิเศษ เช่น ผักกลิ่นฉุน 5 ชนิด */
  specialList?: { title: string; items: string[]; source?: string };
  venues: FestivalVenue[];
  faq: FestivalFaq[];
  healthNote?: string;
  sources: string[];
  /** วันที่ตรวจเนื้อหาล่าสุด */
  checkedAt: string;
}

export interface Festival {
  slug: string;
  name: string;
  tagline: string;
  goals: GoalSlug[];
  dates: FestivalDate[];
  /** ชื่อวันก่อนงาน (prep) ค่าเริ่มต้น วันล้างท้อง เช่น ตรุษจีน = วันจ่าย */
  prepLabel?: string;
  /** ภาพจริงพร้อมเครดิต (ห้ามใช้ภาพ AI จาก mockup) sourceUrl = หน้าไฟล์ต้นทางสำหรับแสดงที่มาและสัญญาอนุญาต */
  image?: { src: string; alt: string; credit: string; sourceUrl?: string };
  /** ต่อท้ายชื่อใน title ของหน้า (ค่าเริ่มต้น: วันไหน ข้อควรรู้ และงานทั่วไทย) */
  seoTitle?: string;
  /** สถานที่ในเว็บที่แสดงในหัวข้อ ไหว้ที่ไหนดี (deity = กลุ่ม/หมวดเทพ เช่น family:chinese) */
  placeFilter?: { deity?: string; goal?: GoalSlug } | null;
  content?: FestivalContent;
}


/** ชื่อสั้นสำหรับการ์ด */
export const provinceShortName = (slug: string) =>
  slug === 'bangkok' ? 'กรุงเทพฯ' : (PROVINCES[slug] ?? slug);

/** หา slug จากชื่อไทย (รับ "กรุงเทพฯ" ด้วย) */
export function provinceSlugFromThai(name: string): string | undefined {
  const n = name.trim().replace(/^จังหวัด/, '');
  if (n === 'กรุงเทพฯ' || n === 'กทม.') return 'bangkok';
  return Object.keys(PROVINCES).find((slug) => PROVINCES[slug] === n);
}
